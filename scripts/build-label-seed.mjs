// Builds the Label Studio seed from the Vistaprint export (Brent, 25 Nov 2026).
//
//   node scripts/build-label-seed.mjs path/to/technomed-labels-export.json
//
// Writes api/_labelSeed.js (the 94 labels, tidied by importLabel, and the
// logos' names and sizes) and api/_labelSeedLogos.js (the logos as data URIs,
// loaded only while seeding). The export repeats the same picture under
// several keys; each picture is kept once and every label points at it.
// The 7 "others" (cards and so on) are left out.

import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { importLabel } from '../src/labels/model.js'

const file = process.argv[2]
if (!file) { console.error('Usage: node scripts/build-label-seed.mjs export.json'); process.exit(1) }
const exp = JSON.parse(readFileSync(file, 'utf8'))

// What each picture is, by the key it first appears under in the 25 Nov export.
const NAMES = {
  i0: ['seaspine', 'SeaSpine'], i1: ['device', 'Device Technologies'], i2: ['technomed', 'TechnoMed'],
  i3: ['signus', 'SIGNUS'], i4: ['e4', 'E4 Surgical'], i5: ['kt', 'KT Medical'], i6: ['orthofix', 'Orthofix'],
  i7: ['reform', 'Precision Spine Reform'], i14: ['reform-small', 'Precision Spine Reform (small)'], i15: ['e4-small', 'E4 Surgical (small)']
}

function pngSize(b64) {
  const buf = Buffer.from(b64, 'base64')
  if (buf.readUInt32BE(12) !== 0x49484452) throw new Error('not a PNG')
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) }
}

const byHash = new Map()
const keyMap = {}
const logos = []
const data = {}
for (const img of exp.images) {
  const hash = createHash('sha1').update(img.data).digest('hex')
  if (!byHash.has(hash)) {
    const [k, name] = NAMES[img.k] || [`logo-${img.k}`, img.k]
    const { w, h } = pngSize(img.data.split(',')[1])
    byHash.set(hash, k)
    logos.push({ k, name, w, h, type: 'image/png' })
    data[k] = img.data
  }
  keyMap[img.k] = byHash.get(hash)
}

const labels = exp.labels.map(l => importLabel(l, keyMap))
const checks = labels.filter(l => l.check).map(l => `${l.name}: ${l.check}`)

const head = `// Generated by scripts/build-label-seed.mjs from the Vistaprint export of
// 25 Nov 2026 — do not edit by hand. Seeded into Redis once (api/_labels.js).\n`
writeFileSync('api/_labelSeed.js', `${head}\nexport const SEED_LOGOS = ${JSON.stringify(logos, null, 1)}\n\nexport const SEED_LABELS = ${JSON.stringify(labels)}\n`)
writeFileSync('api/_labelSeedLogos.js', `${head}// The logos themselves, imported only while seeding.\n\nexport const LOGO_DATA = ${JSON.stringify(data, null, 1)}\n`)
console.log(`${labels.length} labels, ${logos.length} distinct logos (${exp.images.length} in the export)`)
console.log('To check:', checks)
